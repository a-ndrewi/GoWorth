import { readFile, writeFile } from "node:fs/promises";

const [citiesPath, countriesPath, admin1Path] = process.argv.slice(2);
if (!citiesPath || !countriesPath || !admin1Path) throw new Error("Pass GeoNames cities5000.txt, countryInfo.txt, and admin1CodesASCII.txt paths.");

const countryRows = (await readFile(countriesPath, "utf8")).split(/\r?\n/)
  .filter((line) => line && !line.startsWith("#"))
  .map((line) => line.split("\t"));
const countries = countryRows.filter((row) => /^[A-Z]{2}$/.test(row[0]) && row[4] && !["AN", "CS"].includes(row[0]))
  .map((row) => ({ code: row[0], name: row[4], capital: row[5], continent: row[8] }));
const byCountry = Object.fromEntries(countries.map((country) => [country.code, []]));
const usStates = (await readFile(admin1Path, "utf8")).split(/\r?\n/)
  .filter((line) => /^US\.[A-Z]{2}\t/.test(line))
  .map((line) => {
    const [key, name] = line.split("\t");
    return { code: key.slice(3), name };
  }).sort((a, b) => a.name.localeCompare(b.name));
const usStateCodes = new Set(usStates.map((state) => state.code));

for (const line of (await readFile(citiesPath, "utf8")).split(/\r?\n/)) {
  if (!line) continue;
  const fields = line.split("\t");
  const [id, name, , , lat, lon, , , countryCode] = fields;
  if (!byCountry[countryCode] || !name || !Number.isFinite(Number(lat)) || !Number.isFinite(Number(lon))) continue;
  const city = [Number(id), name, Number(lat), Number(lon), Number(fields[14]) || 0];
  if (countryCode === "US" && usStateCodes.has(fields[10])) city.push(fields[10]);
  byCountry[countryCode].push(city);
}
for (const cities of Object.values(byCountry)) cities.sort((a, b) => b[4] - a[4] || a[1].localeCompare(b[1]));
countries.sort((a, b) => a.name.localeCompare(b.name));

const header = `// GeoNames cities5000, countryInfo, and admin1CodesASCII, CC BY 4.0.\n// https://download.geonames.org/export/dump/readme.txt\n// Generated by scripts/import-geonames.mjs; update from the source snapshots.\n`;
const output = `${header}export type CityRow = [id: number, name: string, latitude: number, longitude: number, population: number, usStateCode?: string];\nexport const countryRows: { code: string; name: string; capital: string; continent: string }[] = ${JSON.stringify(countries)};\nexport const usStateRows: { code: string; name: string }[] = ${JSON.stringify(usStates)};\nexport const citiesByCountry: Record<string, CityRow[]> = ${JSON.stringify(byCountry)};\n`;
await writeFile(new URL("../src/data/world-geography.ts", import.meta.url), output);
console.log(`Imported ${countries.length} countries and ${Object.values(byCountry).reduce((sum, cities) => sum + cities.length, 0)} cities.`);
